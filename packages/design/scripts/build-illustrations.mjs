/**
 * Turn the Open Peeps SVGs into a TypeScript module.
 *
 * In the app these were read with Vite's `import.meta.glob('*.svg', {query:
 * '?raw', eager: true})`, which is a bundler feature and not a language one.
 * The package is built with `tsc`, which has no idea what a `?raw` import is —
 * so the component that worked in the app would have shipped a `dist` referring
 * to twenty-one modules that do not exist.
 *
 * That is the general shape of the packaging problem and worth naming: code
 * written inside a bundler can depend on the bundler without ever saying so.
 * Generating a plain module removes the dependency instead of documenting it.
 *
 * Inlined rather than fetched, as before: an illustration appears on an empty
 * state and a first run, which are exactly the moments a request is most likely
 * to fail.
 *
 *   node scripts/build-illustrations.mjs ../../../tf/dashboard/src/illustrations
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const from = resolve(here, process.argv[2] ?? '../../../../tf/dashboard/src/illustrations')

const files = readdirSync(from)
  .filter((f) => f.endsWith('.svg'))
  .sort()

if (files.length === 0) throw new Error(`no SVGs under ${from}`)

const entries = files.map((f) => {
  const name = basename(f, '.svg')
  // The SVGs carry `currentColor` and the theme's tokens, so they are not
  // touched here beyond collapsing the whitespace a hand-authored file carries.
  const svg = readFileSync(join(from, f), 'utf8').replace(/\n\s*/g, ' ').trim()
  return { name, svg }
})

const out = `/* Generated by scripts/build-illustrations.mjs. Do not edit by hand. */

/**
 * The art, inlined.
 *
 * ~240 KB of SVG, which is most of this package's weight — so it lives in its
 * own module referenced only by \`Illustration\`. A bundler that tree-shakes the
 * component away drops the art with it, and an app that never draws an empty
 * state never pays for one.
 */
export const ILLUSTRATIONS = [
${entries.map((e) => `  '${e.name}',`).join('\n')}
] as const

export type IllustrationName = (typeof ILLUSTRATIONS)[number]

export const ILLUSTRATION_SVG: Record<IllustrationName, string> = {
${entries.map((e) => `  ${e.name}: ${JSON.stringify(e.svg)},`).join('\n')}
}
`

const target = resolve(here, '../src/illustrations.ts')
writeFileSync(target, out)
console.log(`${entries.length} illustrations, ${(out.length / 1024).toFixed(0)} KB`)
